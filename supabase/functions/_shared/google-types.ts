const SET = new Set(GOOGLE_TYPES_A);

/** O tipo vale como `includedType`? ("cafe" sim; "waterfall" não existe; "natural_feature" é da Tabela B.) */
export function isGoogleType(type: string): boolean {
  return SET.has(type);
}

/**
 * O tipo do app de um lugar do Google, pelos tipos dele (o `primaryType` primeiro, depois os outros):
 * o que a parada escolhida ganha, como `kindOfCategories` faz com as categorias da Geoapify.
 */
export function kindOfGoogleTypes(
  types: readonly string[],
): 'nature' | 'winery' | 'hotel' | 'food' | 'event' | 'city' | 'fuel' | 'other' {
  const has = (...wanted: string[]) => types.some((t) => wanted.includes(t));
  if (has('lodging', 'hotel', 'motel', 'inn', 'hostel', 'guest_house', 'bed_and_breakfast'))
    return 'hotel';
  if (has('campground', 'camping_cabin', 'rv_park', 'farmstay', 'cottage', 'resort_hotel'))
    return 'hotel';
  if (has('winery', 'vineyard', 'wine_bar')) return 'winery';
  if (has('gas_station', 'electric_vehicle_charging_station', 'rest_stop', 'truck_stop'))
    return 'fuel';
  if (
    types.some(
      (t) =>
        t.endsWith('_restaurant') ||
        t.endsWith('_shop') ||
        t === 'restaurant' ||
        t === 'cafe' ||
        t === 'bakery' ||
        t === 'bar' ||
        t === 'pub' ||
        t === 'brewery' ||
        t === 'brewpub' ||
        t === 'food_court' ||
        t === 'diner' ||
        t === 'bistro' ||
        t === 'cafeteria' ||
        t === 'deli' ||
        t === 'confectionery' ||
        t === 'steak_house' ||
        t === 'tea_house' ||
        t === 'food',
    )
  )
    return 'food';
  if (
    has(
      'park',
      'national_park',
      'state_park',
      'city_park',
      'hiking_area',
      'nature_preserve',
      'beach',
      'lake',
      'river',
      'mountain_peak',
      'woods',
      'scenic_spot',
      'observation_deck',
      'zoo',
      'wildlife_park',
      'wildlife_refuge',
      'botanical_garden',
      'garden',
      'natural_feature',
      'picnic_ground',
      'island',
    )
  )
    return 'nature';
  if (
    has(
      'museum',
      'art_museum',
      'history_museum',
      'art_gallery',
      'historical_landmark',
      'historical_place',
      'cultural_landmark',
      'monument',
      'castle',
      'church',
      'place_of_worship',
      'plaza',
      'locality',
      'administrative_area_level_2',
    )
  )
    return 'city';
  if (
    has(
      'amusement_park',
      'water_park',
      'aquarium',
      'event_venue',
      'performing_arts_theater',
      'concert_hall',
      'market',
      'farmers_market',
      'flea_market',
      'shopping_mall',
      'movie_theater',
      'tourist_attraction',
    )
  )
    return 'event';
  return 'other';
}
